import {readFile} from 'node:fs/promises';
const text=await readFile(new URL('../wrangler.jsonc',import.meta.url),'utf8');
const config=JSON.parse(text);
const problems=[];
if(config.vars?.ENVIRONMENT!=='production'||config.vars?.LOCAL_ADMIN)problems.push('本番環境の設定が必要です。');
if(config.vars?.AUTH_MODE!=='password')problems.push('管理者パスワード認証を設定してください。');
if(!config.secrets?.required?.includes('ADMIN_AUTH_SECRET'))problems.push('管理者認証の秘密設定が必要です。');
if(config.d1_databases?.[0]?.database_id==='00000000-0000-0000-0000-000000000000')problems.push('本番D1データベースを接続してください。');
if(!config.assets?.run_worker_first)problems.push('全ファイルに公開期間の判定が必要です。');
if(problems.length){console.error(problems.join('\n'));process.exitCode=1;}else console.log('Production configuration ready.');
